/// <summary>
/// 渲染层级枚举
/// 值越大渲染越靠后（越在上层显示），值越小渲染越靠前（越在下层显示）
/// 场景人物和场景建筑是动态层级，根据位置变化，不在此枚举中
/// </summary>
public enum 渲染层级
{
    /// <summary>
    /// 场景地板，最底层
    /// </summary>
    场景地板 = 100,
    
    /// <summary>
    /// 网格辅助线层级
    /// </summary>
    网格辅助线 = 80,
    
    /// <summary>
    /// 移动范围、技能攻击范围
    /// </summary>
    移动范围 = 95,
    
    /// <summary>
    /// 交互区域（移动目标区域等）
    /// </summary>
    交互区域 = 90,
    
    /// <summary>
    /// 鼠标区域（范围技能指示圈、选中单位高亮）
    /// </summary>
    鼠标区域 = 85,
}
