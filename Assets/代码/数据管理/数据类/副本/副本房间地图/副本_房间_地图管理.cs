    public void 计算格子上单位的可移动范围(副本单位脚本 副本单位)
    {
        if(副本单位.可移动范围字典 == null)
            副本单位.可移动范围字典 = new Dictionary<副本_房间_地图_格子, List<副本_房间_地图_格子>>();
        副本单位.可移动范围字典.Clear();
        副本单位.可移动范围格子哈希集.Clear();
        副本_房间_地图_格子 单位所在格子 = 副本单位.单位.所在格子;
        int 每点行动力可移动格子距离 = 副本单位.单位.角色属性.敏捷;
        float 总可移动格子距离 = 副本单位.单位.剩余行动力 * 每点行动力可移动格子距离;
        if(总可移动格子距离<=0) return;

        Queue<副本_房间_地图_格子> 待处理队列 = new Queue<副本_房间_地图_格子>();
        Dictionary<副本_房间_地图_格子, float> 距离字典 = new Dictionary<副本_房间_地图_格子, float>();
        HashSet<副本_房间_地图_格子> 已访问集合 = new HashSet<副本_房间_地图_格子>();

        待处理队列.Enqueue(单位所在格子);
        距离字典[单位所在格子] = 0;
        while (待处理队列.Count > 0)
        {
            副本_房间_地图_格子 当前格子 = 待处理队列.Dequeue();
            float 当前距离 = 距离字典[当前格子];
            if (已访问集合.Contains(当前格子) || 当前距离 > 总可移动格子距离)
            {
                continue;
            }
            已访问集合.Add(当前格子);
            bool 符合移动条件 = true;
            副本_房间_地图_格子[] 范围格子数组 = {
            当前格子,
            目标格子上(当前格子),
            目标格子下(当前格子),
            目标格子左(当前格子),
            目标格子右(当前格子),
            目标格子左上(当前格子),
            目标格子右上(当前格子),
            目标格子左下(当前格子),
            目标格子右下(当前格子)
        };
            for (int i = 0; i < 9; i++)
            {
                if (范围格子数组[i] == null)
                {
                    符合移动条件 = false;
                    break;
                }
                if (范围格子数组[i].存在单位 && 范围格子数组[i].单位 != 副本单位.单位)
                {
                    符合移动条件 = false;
                    break;
                }
            }

            if (符合移动条件)
            {
                for (int i = 0; i < 9; i++)
                {
                    var r = 范围格子数组[i];
                    副本单位.可移动范围格子哈希集.Add(r);
                    if(i==0) continue;
                    if (r != null && !已访问集合.Contains(r) && !距离字典.ContainsKey(r))
                    {
                        float 移动消耗 = (i <= 4) ? 1 : 1.5f; // 1234是上下左右+1，5678是角落+2
                        float 新距离 = 当前距离 + 移动消耗;
                        待处理队列.Enqueue(r);
                        距离字典[r] = 新距离;
                    }
                }
                if (当前格子 != 单位所在格子)
                {
                    if (!副本单位.可移动范围字典.ContainsKey(当前格子))
                        副本单位.可移动范围字典[当前格子] = new List<副本_房间_地图_格子>();
                    副本单位.可移动范围字典[当前格子].AddRange(范围格子数组);
                }
            }
        }
    }

    public void 计算技能的攻击范围(副本单位脚本 副本单位, 技能类 技能)
    {
        if (副本单位 == null || 副本单位.单位 == null || 技能 == null) return;
        if (副本单位.技能攻击范围格子哈希集 == null) 副本单位.技能攻击范围格子哈希集 = new HashSet<副本_房间_地图_格子>();
        副本单位.技能攻击范围格子哈希集.Clear();

        var 单位所在格子 = 副本单位.单位.所在格子;
        if (单位所在格子 == null) return;

        float 射程 = 技能.射程;
        if (射程 <= 0) return;
        float 最大格子距离 = 射程 * 3f;

        Queue<副本_房间_地图_格子> 待处理队列 = new Queue<副本_房间_地图_格子>();
        Dictionary<副本_房间_地图_格子, float> 距离字典 = new Dictionary<副本_房间_地图_格子, float>();
        HashSet<副本_房间_地图_格子> 已访问集合 = new HashSet<副本_房间_地图_格子>();

        待处理队列.Enqueue(单位所在格子);
        距离字典[单位所在格子] = 0;

        while (待处理队列.Count > 0)
        {
            var 当前格子 = 待处理队列.Dequeue();
            float 当前距离 = 距离字典[当前格子];
            if (已访问集合.Contains(当前格子) || 当前距离 > 最大格子距离) continue;
            已访问集合.Add(当前格子);

            副本单位.技能攻击范围格子哈希集.Add(当前格子);

            if (当前距离 >= 最大格子距离) continue;

            var 上 = 目标格子上(当前格子);
            var 下 = 目标格子下(当前格子);
            var 左 = 目标格子左(当前格子);
            var 右 = 目标格子右(当前格子);
            var 左上 = 目标格子左上(当前格子);
            var 右上 = 目标格子右上(当前格子);
            var 左下 = 目标格子左下(当前格子);
            var 右下 = 目标格子右下(当前格子);

            副本_房间_地图_格子[] 邻居数组 = { 上, 下, 左, 右, 左上, 右上, 左下, 右下 };
            for (int i = 0; i < 邻居数组.Length; i++)
            {
                var 邻居 = 邻居数组[i];
                if (邻居 == null || 已访问集合.Contains(邻居) || 距离字典.ContainsKey(邻居)) continue;
                float 移动消耗 = (i <= 3) ? 1f : 1.5f;
                float 新距离 = 当前距离 + 移动消耗;
                if (新距离 > 最大格子距离) continue;
                距离字典[邻居] = 新距离;
                待处理队列.Enqueue(邻居);
            }
        }
    }

