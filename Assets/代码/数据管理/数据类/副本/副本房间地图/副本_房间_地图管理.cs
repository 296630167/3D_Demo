    /// <summary>
    /// 分配敌人单位 - 从最后一个格子往前分配
    /// </summary>
    private IEnumerator 分配敌人单位(副本_房间 房间)
    {
        int 起点行 = 行数 - 2;
        int 起点列 = 列数 - 2;
        
        switch(房间.房间类型)
        {
            case 副本房间类型.战斗:
                // 首先分配首领
                foreach(var 单位 in 房间.首领列表)
                {
                    if (分配单个敌人单位(单位, ref 起点行, ref 起点列))
                    {
                        // 分配成功，继续下一个
                    }
                }
                // 然后分配精英
                foreach(var 单位 in 房间.精英列表)
                {
                    if (分配单个敌人单位(单位, ref 起点行, ref 起点列))
                    {
                        // 分配成功，继续下一个
                    }
                }
                // 最后分配小怪
                foreach(var 单位 in 房间.小怪列表)
                {
                    if (分配单个敌人单位(单位, ref 起点行, ref 起点列))
                    {
                        // 分配成功，继续下一个
                    }
                }
                break;
        }
        yield return null;
    }

    /// <summary>
    /// 分配单个敌人单位到格子上
    /// </summary>
    private bool 分配单个敌人单位(副本单位 单位, ref int 起点行, ref int 起点列)
    {
        // 循环尝试找到可用位置
        while (起点行 >= 1)
        {
            if (在范围内(起点行, 起点列))
            {
                副本_房间_地图_格子 当前格子 = 格子数组[起点行, 起点列];
                if (检查点位能否放置单位(当前格子))
                {
                    确定单位坐标(单位, 当前格子);
                    起点列 -= 3;
                    if (起点列 < 1)
                    {
                        起点行 -= 3;
                        起点列 = 列数 - 2;
                    }
                    return true;
                }
            }
            // 当前位置不可用，尝试下一个位置
            起点列 -= 3;
            if (起点列 < 1)
            {
                起点行 -= 3;
                起点列 = 列数 - 2;
            }
        }
        // 没有可用位置
        Debug.LogWarning($"无法为敌人单位分配位置，地图可能已满。");
        return false;
    }
    private bool 检查点位能否放置单位(副本_房间_地图_格子 当前点位)
    {
        if (当前点位 == null) return false;
        
        var 上 = 目标格子上(当前点位);
        var 下 = 目标格子下(当前点位);
        var 左 = 目标格子左(当前点位);
        var 右 = 目标格子右(当前点位);
        var 左上 = 目标格子左上(当前点位);
        var 右上 = 目标格子右上(当前点位);
        var 左下 = 目标格子左下(当前点位);
        var 右下 = 目标格子右下(当前点位);
        
        // 检查所有相邻格子是否存在且未被占用
        return !当前点位.存在单位 &&
               上 != null && !上.存在单位 &&
               下 != null && !下.存在单位 &&
               左 != null && !左.存在单位 &&
               右 != null && !右.存在单位 &&
               左上 != null && !左上.存在单位 &&
               右上 != null && !右上.存在单位 &&
               左下 != null && !左下.存在单位 &&
               右下 != null && !右下.存在单位;
    }
