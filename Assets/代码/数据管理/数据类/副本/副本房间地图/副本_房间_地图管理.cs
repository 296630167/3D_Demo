    public int 列数;
    public 副本_房间_地图_格子[,] 格子数组;
    // 把地图 上下左右 中心的五个点位单独写出来 由于游戏里 每个单位占用的格子是3*3的 正数或者倒数第二行或者列 才开始计算点位
    public 副本_房间_地图_格子 中心格子 => 格子数组[中心行, 中心列];
    public 副本_房间_地图_格子 上边中心 => 格子数组[行数 - 2, 中心列];
    public 副本_房间_地图_格子 下边中心 => 格子数组[1, 中心列];
    public 副本_房间_地图_格子 左边中心 => 格子数组[中心行, 1];
    public 副本_房间_地图_格子 右边中心 => 格子数组[中心行, 列数 - 2];
    public List<副本_房间_地图_格子> 初始状态格子列表;
    private bool 在范围内(int 行, int 列)
    {
        return 行 >= 0 && 行 < 行数 && 列 >= 0 && 列 < 列数;
    }
    public 副本_房间_地图_格子 取格子或空(int 行, int 列)
    {
        return 在范围内(行, 列) ? 格子数组[行, 列] : null;
    }
    public 副本_房间_地图_格子 目标格子上(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行 + 1, 检查格子.列);
    public 副本_房间_地图_格子 目标格子下(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行 - 1, 检查格子.列);
    public 副本_房间_地图_格子 目标格子左(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行, 检查格子.列 - 1);
    public 副本_房间_地图_格子 目标格子右(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行, 检查格子.列 + 1);
    public 副本_房间_地图_格子 目标格子左上(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行 + 1, 检查格子.列 - 1);
    public 副本_房间_地图_格子 目标格子右上(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行 + 1, 检查格子.列 + 1);
    public 副本_房间_地图_格子 目标格子左下(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行 - 1, 检查格子.列 - 1);
    public 副本_房间_地图_格子 目标格子右下(副本_房间_地图_格子 检查格子) => 取格子或空(检查格子.行 - 1, 检查格子.列 + 1);
    public 副本_房间_地图管理(int 行数 = 30, int 列数 = 30)
    {
        this.行数 = 行数;
        this.列数 = 列数;
        this.中心行 = 行数 / 2;
        this.中心列 = 列数 / 2;
        this.格子数组 = new 副本_房间_地图_格子[行数, 列数];
        for (int 行 = 0; 行 < 行数; 行++)
        {
            for (int 列 = 0; 列 < 列数; 列++)
            {
                this.格子数组[行, 列] = new 副本_房间_地图_格子(行, 列);
            }
        }
    }
    public IEnumerator 初始化地图格子()
    {
        初始状态格子列表 = new List<副本_房间_地图_格子>();
        for (int 行 = 0; 行 < 行数; 行++)
        {
            for (int 列 = 0; 列 < 列数; 列++)
            {
                this.格子数组[行, 列].存在单位 = false;
                this.格子数组[行, 列].单位 = null;
            }
        }
        yield return null;
    }
    public IEnumerator 初始化新房间数据(副本_房间 房间, 副本_房间 上一个房间, 副本单位[] 副本上阵单位数组)
    {
        // 1. 初始化地图格子
        yield return Mono方法管理器.开启协程(初始化地图格子());
        // 2. 分配建筑方法 先暂时给四个角往里一个格子的位置 放个柱子 柱子占地2*2
        yield return Mono方法管理器.开启协程(分配建筑物(房间));
        // 3. 分配玩家单位方法  从(1,1)格子开始 找到符合条件的格子 依次给玩家单位分配位置
        if (副本上阵单位数组 != null && 副本上阵单位数组.Length > 0)
        {
            yield return Mono方法管理器.开启协程(分配玩家单位坐标(副本上阵单位数组, 房间, 上一个房间));
        }
        // 4. 分配中立单位方法 暂时占位 方法空着
        yield return Mono方法管理器.开启协程(分配中立单位(房间));
        // 5. 分配敌人单位方法 从最后一个格 往前分配
        yield return Mono方法管理器.开启协程(分配敌人单位(房间));
        yield return null;
    }

    /// <summary>
    /// 分配建筑物（柱子）- 在四个角往里3个格子的位置放置，占地2x2
    /// </summary>
    private IEnumerator 分配建筑物(副本_房间 房间)
    {
        // 清空之前的建筑列表
        房间.建筑列表.Clear();
        
        // 柱子离边至少3个格子，占地2x2
        // 左下角柱子 (3,3)
        分配单个建筑物(房间, 副本建筑类型.柱子, 3, 3, 2, 2);
        // 右下角柱子 (3, 列数-5)
        分配单个建筑物(房间, 副本建筑类型.柱子, 3, 列数 - 5, 2, 2);
        // 左上角柱子 (行数-5, 3)
        分配单个建筑物(房间, 副本建筑类型.柱子, 行数 - 5, 3, 2, 2);
        // 右上角柱子 (行数-5, 列数-5)
        分配单个建筑物(房间, 副本建筑类型.柱子, 行数 - 5, 列数 - 5, 2, 2);
        
        // 随机分配4个柱子（测试用）
        随机分配柱子(房间, 4);
        
        yield return null;
    }
    
    /// <summary>
    /// 随机分配柱子（测试用，后续可注释掉）
    /// </summary>
    private void 随机分配柱子(副本_房间 房间, int 数量)
    {
        int 已分配数量 = 0;
        int 最大尝试次数 = 100;
        int 尝试次数 = 0;
        
        // 可用范围：离边3个格子
        int 最小行 = 3;
        int 最大行 = 行数 - 5;
        int 最小列 = 3;
        int 最大列 = 列数 - 5;
        
        while (已分配数量 < 数量 && 尝试次数 < 最大尝试次数)
        {
            尝试次数++;
            
            int 随机行 = UnityEngine.Random.Range(最小行, 最大行 + 1);
            int 随机列 = UnityEngine.Random.Range(最小列, 最大列 + 1);
            
            // 检查该位置和占地范围是否可用
            if (检查建筑位置可用(随机行, 随机列, 2, 2))
            {
                分配单个建筑物(房间, 副本建筑类型.柱子, 随机行, 随机列, 2, 2);
                已分配数量++;
            }
        }
    }
    
    /// <summary>
    /// 检查建筑位置是否可用
    /// </summary>
    private bool 检查建筑位置可用(int 起始行, int 起始列, int 占地行数, int 占地列数)
    {
        for (int 行偏移 = 0; 行偏移 < 占地行数; 行偏移++)
        {
            for (int 列偏移 = 0; 列偏移 < 占地列数; 列偏移++)
            {
                int 行 = 起始行 + 行偏移;
                int 列 = 起始列 + 列偏移;
                if (!在范围内(行, 列)) return false;
                副本_房间_地图_格子 格子 = 格子数组[行, 列];
                if (格子 == null || 格子.存在单位) return false;
            }
        }
        return true;
    }
    
    /// <summary>
    /// 分配单个建筑物，创建建筑实例并记录到房间
    /// </summary>
    private void 分配单个建筑物(副本_房间 房间, 副本建筑类型 建筑类型, int 起始行, int 起始列, int 占地行数, int 占地列数)
    {
        // 获取中心格子
        副本_房间_地图_格子 中心格子 = 格子数组[起始行, 起始列];
        
        // 创建建筑实例
        副本建筑 建筑 = new 副本建筑(建筑类型, 中心格子, 占地行数, 占地列数);
        
        // 分配占地并记录到建筑的占用格子列表
        for (int 行偏移 = 0; 行偏移 < 占地行数; 行偏移++)
        {
            for (int 列偏移 = 0; 列偏移 < 占地列数; 列偏移++)
            {
                int 行 = 起始行 + 行偏移;
                int 列 = 起始列 + 列偏移;
                if (在范围内(行, 列))
                {
                    副本_房间_地图_格子 格子 = 格子数组[行, 列];
                    格子.存在单位 = true;
                    格子.单位 = null; // 建筑物不是单位，但占据格子
                    // 添加到建筑的占用格子列表
                    建筑.占用格子列表.Add(格子);
                }
            }
        }
        
        // 将建筑添加到房间的建筑列表
        房间.建筑列表.Add(建筑);
    }

    /// <summary>
    /// 分配玩家单位坐标 - 从(1,1)格子开始 找到符合条件的格子 依次给玩家单位分配位置
    /// </summary>
    public IEnumerator 分配玩家单位坐标(副本单位[] 副本上阵单位数组, 副本_房间 当前房间, 副本_房间 上一个房间)
    {
        if (副本上阵单位数组 == null || 副本上阵单位数组.Length == 0)
        {
            yield break;
        }

        int 起点行 = 1;
        int 起点列 = 1;
        int 最大行 = 行数 - 2;
        int 最大列 = 列数 - 2;

        foreach (var 单位 in 副本上阵单位数组)
        {
            if (!单位.存在单位) continue;

            bool 已分配 = false;
            // 从当前起点开始查找可用格子
            for (int 行 = 起点行; 行 <= 最大行 && !已分配; 行 += 3)
            {
                for (int 列 = (行 == 起点行 ? 起点列 : 1); 列 <= 最大列; 列 += 3)
                {
                    if (在范围内(行, 列))
                    {
                        副本_房间_地图_格子 当前格子 = 格子数组[行, 列];
                        if (检查点位能否放置单位(当前格子))
                        {
                            分配格子单位(单位, 当前格子);
                            已分配 = true;
                            // 更新起点为下一个可能的位置
                            起点列 = 列 + 3;
                            if (起点列 > 最大列)
                            {
                                起点行 = 行 + 3;
                                起点列 = 1;
                            }
                            else
                            {
                                起点行 = 行;
                            }
                            break;
                        }
                    }
                }
            }
            // 如果找不到位置，记录警告
            if (!已分配)
            {
                Debug.LogWarning($"无法为玩家单位分配位置，地图可能已满。");
            }
        }
        yield return null;
    }



